interface Def {
  slug: string;
  name: string;
  subcategory: string;
  summary: string;
  description: string;
  specifications: ProductSpec[];
  variantAxes: string[];
  variants: Product['variants'];
  page: number;
  section: string;
  standard?: string;
  /** image file name under assets/products/machine-tool-accessories (without .webp) */
  img?: string | string[];
  otherSources?: ProductSource[];
  featured?: boolean;
  reviewNote?: string;
}

const P = (d: Def): Product => ({
  slug: d.slug,
  name: d.name,
  category: MTA,
  subcategory: d.subcategory,
  brand: BRAND,
  standard: d.standard,
  summary: d.summary,
  description: d.description,
  images: (d.img ? (Array.isArray(d.img) ? d.img : [d.img]) : []).map(
    (f) => `assets/products/${MTA}/${f}.webp`,
  ),
  specifications: d.specifications,
  variantAxes: d.variantAxes,
  variants: d.variants,
  source: { doc: 'RR-2025', page: d.page, section: d.section },
  otherSources: d.otherSources,
  featured: d.featured,
  reviewNote: d.reviewNote,
});

const s26 = (page: number, section: string): ProductSource => ({ doc: 'RR-2026', page, section });

/** Two-axis table: [[rowValue, [colValues…]], …] → variants (only listed cells). */
const g = (
  axes: [string, string],
  spec: [string, string[]][],
  label?: (a: Record<string, string>) => string,
) => rows(axes, spec.flatMap(([a, bs]) => bs.map((b) => [a, b])), label);

/** Three-axis: [[a, b, [c…]], …]. */
const g3 = (
  axes: [string, string, string],
  spec: [string, string, string[]][],
  label?: (a: Record<string, string>) => string,
) => rows(axes, spec.flatMap(([a, b, cs]) => cs.map((c) => [a, b, c])), label);

const one = (axis: string, values: string[]) => rows([axis], values.map((v) => [v]));

const ER = (...n: number[]) => n.map((x) => `ER-${x}`);
const FMB = (...n: (number | string)[]) => n.map((x) => `FMB-${x}`);
const SLA = (...n: number[]) => n.map((x) => `SLA-${x}`);
const MT = (...n: number[]) => n.map((x) => `MT-${x}`);

